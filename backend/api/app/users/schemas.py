"""Pydantic models for user data returned by the API, and the admin's people management."""

from datetime import date, datetime

from pydantic import BaseModel, ConfigDict, Field

from app.overview.schemas import Progress

ROLE_PATTERN = "^(admin|manager|employee)$"


class UserPublic(BaseModel):
    """The fields of a user that may be sent to a client. Never the hash."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    username: str
    first_name: str
    last_name: str
    email: str
    job_title: str | None = None
    role: str


class UserCreate(BaseModel):
    """
    Admin creates an account (ADMIN.md §2). The username is generated by the server; the
    temporary password is set by the admin and shown once in the credentials dialog.
    """

    first_name: str = Field(min_length=1, max_length=100)
    last_name: str = Field(min_length=1, max_length=100)
    email: str = Field(min_length=3, max_length=200)
    job_title: str | None = Field(default=None, max_length=100)
    role: str = Field(pattern=ROLE_PATTERN)
    department_id: int | None = None
    manager_id: int | None = None
    hourly_rate: float = Field(default=0, ge=0)
    password: str = Field(min_length=8, max_length=128)


class MeUpdate(BaseModel):
    """PATCH /me: the only account fields a person edits themselves (EMPLOYEE.md §6.6)."""

    first_name: str | None = Field(default=None, min_length=1, max_length=100)
    last_name: str | None = Field(default=None, min_length=1, max_length=100)
    email: str | None = Field(default=None, min_length=3, max_length=200)


class UserUpdate(BaseModel):
    """Fields a PATCH may change. Admin: any of them. Manager: name and email of a direct report."""

    first_name: str | None = Field(default=None, min_length=1, max_length=100)
    last_name: str | None = Field(default=None, min_length=1, max_length=100)
    email: str | None = Field(default=None, min_length=3, max_length=200)
    job_title: str | None = Field(default=None, max_length=100)
    role: str | None = Field(default=None, pattern=ROLE_PATTERN)
    department_id: int | None = None
    manager_id: int | None = None
    hourly_rate: float | None = Field(default=None, ge=0)


class UserRow(BaseModel):
    """One person in the People table (admin) or My team table (manager)."""

    id: int
    code: str
    username: str
    first_name: str
    last_name: str
    name: str
    email: str
    job_title: str | None = None
    role: str
    department_id: int | None = None
    department: str | None = None
    manager_id: int | None = None
    manager_name: str | None = None
    hourly_rate: float
    is_archived: bool
    created_at: datetime
    team_names: list[str]
    hours_this_week: float
    over_capacity: bool
    cost_this_week: float
    tasks: Progress


class PickablePerson(BaseModel):
    """An employee a manager may put on a team: one of theirs (`manager_id` set) or unassigned (null)."""

    id: int
    name: str
    email: str
    job_title: str | None = None
    manager_id: int | None = None
    hours_this_week: float


class PeopleSearch(BaseModel):
    """GET /employees/search: the first page of matches and how many matched in all."""

    items: list[PickablePerson]
    total: int
    limit: int


class UserProject(BaseModel):
    """A project the person manages or is on, with their task progress in it."""

    id: int
    code: str
    name: str
    department: str
    status: str
    relation: str
    progress: Progress
    planned_hours: float
    actual_hours: float
    actual_cost: float


class UserTeam(BaseModel):
    """A team the person is on (or owns)."""

    id: int
    code: str
    name: str
    manager_name: str


class UserMilestone(BaseModel):
    """The person's task progress inside one milestone."""

    id: int
    name: str
    sequence: int
    status: str
    project_code: str
    progress: Progress


class UserTimeEntry(BaseModel):
    """One of the person's recent time entries."""

    id: int
    work_date: date
    hours: float
    cost: float
    task_code: str
    task_title: str
    project_code: str
    note: str | None = None


class UserDetail(UserRow):
    """The profile side panel: everything in the row plus projects, teams, hours and blockers."""

    projects: list[UserProject]
    teams: list[UserTeam]
    milestones: list[UserMilestone]
    recent_entries: list[UserTimeEntry]
    lifetime_hours: float
    lifetime_cost: float
    direct_reports: int
    blockers: list[str]
    can_archive: bool


class RoleCounts(BaseModel):
    """How many active people hold each role, plus the archived count."""

    admin: int
    manager: int
    employee: int
    archived: int


class UserPage(BaseModel):
    """One page of the people list (ADMIN.md §2: lists are paginated)."""

    items: list[UserRow]
    page: int
    limit: int
    total: int
    counts: RoleCounts


class ManagerOption(BaseModel):
    """An active manager a person can report to."""

    id: int
    name: str


class DepartmentOption(BaseModel):
    """A department a person can belong to."""

    id: int
    name: str
    prefix: str


class UserFormOptions(BaseModel):
    """Choices for the admin's user form."""

    managers: list[ManagerOption]
    departments: list[DepartmentOption]
